"""Pure fault injection functions.

Purpose: Modifies telemetry readings to simulate physical anomalies and device faults.
Inputs: TelemetryMessage, FaultSpec, current timestamp, and optional random generator.
Outputs: Mutated TelemetryMessage adhering to fault signature, or None for comm dropouts.
"""

from __future__ import annotations

import random
from collections.abc import Callable, Sequence
from datetime import datetime
from typing import Any

from backend.common.schemas import TelemetryMessage
from backend.faults.active import get_active_fault_for_device
from backend.faults.models import FaultSpec, FaultType

RAMP_PERIOD_S: float = 300.0  # 5 minutes ramping for thermal inertia
MIN_OVERHEAT_DELTA_C: float = 15.0
MAX_OVERHEAT_DELTA_C: float = 30.0
MIN_GRID_SAG_V: float = 180.0
MAX_GRID_SAG_V: float = 205.0
POWER_THRESHOLD_RELAY_W: float = 200.0


def inject_overheating(
    msg: TelemetryMessage,
    fault: FaultSpec,
    current_ts: datetime,
) -> TelemetryMessage:
    """Inject overheating fault into telemetry with 5-minute thermal ramp.

    Temperature increases 15 to 30 degrees Celsius above expected based on severity,
    ramping linearly over 300 seconds, then holding steady.
    """
    elapsed_s = max(0.0, (current_ts - fault.start_ts).total_seconds())
    ramp_ratio = min(1.0, elapsed_s / RAMP_PERIOD_S)

    delta_c = MIN_OVERHEAT_DELTA_C + (
        (MAX_OVERHEAT_DELTA_C - MIN_OVERHEAT_DELTA_C) * fault.severity
    )
    applied_delta = delta_c * ramp_ratio
    new_temp = round(min(120.0, msg.temperature_c + applied_delta), 2)

    return msg.model_copy(update={"temperature_c": new_temp})


def inject_grid_sag(
    msg: TelemetryMessage,
    fault: FaultSpec,
    rng: random.Random | None = None,
) -> TelemetryMessage:
    """Inject grid voltage sag between 180 V and 205 V with small gaussian noise."""
    base_sag = MAX_GRID_SAG_V - ((MAX_GRID_SAG_V - MIN_GRID_SAG_V) * fault.severity)
    noise = rng.gauss(0.0, 0.5) if rng is not None else 0.0
    sag_v = round(max(MIN_GRID_SAG_V, min(MAX_GRID_SAG_V, base_sag + noise)), 1)

    return msg.model_copy(update={"grid_voltage_v": sag_v})


def inject_relay_stuck(
    msg: TelemetryMessage,
    fault: FaultSpec,
) -> TelemetryMessage:
    """Inject relay stuck condition.

    Relay reports 'open' while generated power is over 200 W, and status transitions to 'warning'.
    """
    del fault  # Signature uniformity across pure injectors
    if msg.ac_power_w > POWER_THRESHOLD_RELAY_W:
        return msg.model_copy(update={"relay_state": "open", "status": "warning"})
    return msg.model_copy(update={"relay_state": "open"})


def inject_comm_dropout(
    msg: TelemetryMessage,
    fault: FaultSpec,
) -> None:
    """Inject communication dropout fault, suppressing message publishing."""
    del msg, fault
    return None


def apply_fault(
    msg: TelemetryMessage,
    fault: FaultSpec,
    current_ts: datetime,
    rng: random.Random | None = None,
) -> TelemetryMessage | None:
    """Dispatcher applying the active fault to a telemetry reading.

    Args:
        msg: Baseline telemetry message generated by inverter.
        fault: Active FaultSpec affecting this device.
        current_ts: Current simulation timestamp.
        rng: Optional pseudo-random generator for noise injection.

    Returns:
        Mutated TelemetryMessage with injected signature, or None if suppressed.
    """
    if fault.fault_type == FaultType.OVERHEATING:
        return inject_overheating(msg, fault, current_ts)
    if fault.fault_type == FaultType.GRID_SAG:
        return inject_grid_sag(msg, fault, rng)
    if fault.fault_type == FaultType.RELAY_STUCK:
        return inject_relay_stuck(msg, fault)
    if fault.fault_type == FaultType.COMM_DROPOUT:
        inject_comm_dropout(msg, fault)
        return None

    raise ValueError(f"Unknown fault type: {fault.fault_type}")


class FaultSession:
    """Coordinates fault resolution, mutation dispatch, and injection notifications."""

    def __init__(
        self,
        faults: Sequence[FaultSpec],
        seed: int = 42,
        on_fault_injected: Callable[[FaultSpec, datetime], Any] | None = None,
    ) -> None:
        self.faults = list(faults)
        self.on_fault_injected = on_fault_injected
        self._rng = random.Random(seed)  # nosec: B311
        self._injected_fault_ids: set[str] = set()

    def __call__(self, msg: TelemetryMessage, current_ts: datetime) -> TelemetryMessage | None:
        """Inject active fault for this message's device if present."""
        active_fault = get_active_fault_for_device(self.faults, msg.device_id, current_ts)
        if active_fault is None:
            return msg

        if active_fault.fault_id not in self._injected_fault_ids:
            self._injected_fault_ids.add(active_fault.fault_id)
            if self.on_fault_injected is not None:
                self.on_fault_injected(active_fault, current_ts)

        return apply_fault(msg, active_fault, current_ts, self._rng)
